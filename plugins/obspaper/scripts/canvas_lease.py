#!/usr/bin/env python3
"""One writer at a time per Canvas, recorded where Obsidian Sync carries it.

Obsidian Sync moves a Canvas between hosts but cannot merge two edits to it, so
whoever writes must be settled before anyone does. The lease is a Markdown file
beside the Canvas: Sync skips dot-files, and syncs files other than Markdown and
Canvas only when "other file types" is switched on, so a Markdown file is the
one form every host is guaranteed to see.
"""

from __future__ import annotations

import json
import os
import socket
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from obs_project import _frontmatter_value, _vault_config_path
from record_action import append_action

LEASE_FILE = "CANVAS_LEASE.md"
TIME_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
BODY = (
    "# Canvas Lease\n\n"
    "Written by `obs_paper.py lease`. Each frontmatter line names one Canvas in this folder and the\n"
    "device allowed to write it until `expires_at` (UTC). An expired line counts as no lease.\n"
    "Do not edit this file by hand, and do not remove another device's line: ask its owner.\n"
)


class LeaseError(ValueError):
    """A lease operation would take writing rights another device holds."""


def device_name(config_path: Path | None = None) -> tuple[str, str]:
    """This host's device name and where it came from.

    It has to be the name given to `ob sync-setup --device-name`, so the name in a
    lease is the name the user sees in Obsidian Sync.
    """
    override = os.environ.get("OBS_PAPER_DEVICE", "").strip()
    if override:
        return override, "OBS_PAPER_DEVICE"
    config = _vault_config_path(config_path)
    if config.is_file():
        try:
            data = json.loads(config.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise LeaseError(f"cannot read obs-paper config {config}: {exc}") from exc
        if isinstance(data, dict) and isinstance(data.get("device"), str) and data["device"].strip():
            return data["device"].strip(), "config"
    return socket.gethostname(), "hostname"


def lease_file(canvas: Path) -> Path:
    return canvas.expanduser().resolve().parent / LEASE_FILE


def lease_required(canvas: Path) -> bool:
    metadata = canvas.expanduser().resolve().parent / "project.md"
    return metadata.is_file() and _frontmatter_value(metadata, "canvas_lease") == "required"


def _format_time(value: datetime) -> str:
    return value.astimezone(timezone.utc).strftime(TIME_FORMAT)


def _parse_time(value: Any, path: Path) -> datetime:
    try:
        return datetime.strptime(value, TIME_FORMAT).replace(tzinfo=timezone.utc)
    except (TypeError, ValueError) as exc:
        raise LeaseError(f"{path} has an unreadable time {value!r}; expected {TIME_FORMAT}") from exc


def _now(now: datetime | None) -> datetime:
    if now is None:
        return datetime.now(timezone.utc).replace(microsecond=0)
    if now.tzinfo is None:
        raise LeaseError("lease time must be timezone-aware")
    return now.astimezone(timezone.utc).replace(microsecond=0)


def _read_entries(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---":
        raise LeaseError(f"{path} has no frontmatter; move it aside rather than guessing who holds the Canvas")
    decoder = json.JSONDecoder()
    entries: list[dict[str, Any]] = []
    for line in lines[1:]:
        if line == "---":
            return entries
        if not line.strip():
            continue
        try:
            key, end = decoder.raw_decode(line)
            if line[end : end + 2] != ": ":
                raise ValueError("missing ': '")
            entry = json.loads(line[end + 2 :])
        except ValueError as exc:
            raise LeaseError(f"{path} has an unreadable lease line {line!r}: {exc}") from exc
        if (
            not isinstance(entry, dict)
            or entry.get("canvas") != key
            or not isinstance(entry.get("device"), str)
            or not entry["device"]
        ):
            raise LeaseError(f"{path} has a malformed lease line {line!r}")
        _parse_time(entry.get("acquired_at"), path)
        _parse_time(entry.get("expires_at"), path)
        entries.append(entry)
    raise LeaseError(f"{path} has unterminated frontmatter")


def _write_entries(path: Path, entries: list[dict[str, Any]]) -> None:
    ordered = sorted(entries, key=lambda entry: (entry["canvas"], entry["device"]))
    lines = ["---"]
    lines.extend(
        f"{json.dumps(entry['canvas'], ensure_ascii=False)}: {json.dumps(entry, ensure_ascii=False)}"
        for entry in ordered
    )
    lines.append("---")
    text = "\n".join(lines) + "\n\n" + BODY
    handle = tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent, prefix=f".{path.name}.", delete=False
    )
    temporary = Path(handle.name)
    try:
        with handle:
            handle.write(text)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def lease_status(
    canvas: Path,
    *,
    device: str | None = None,
    now: datetime | None = None,
    config_path: Path | None = None,
) -> dict[str, Any]:
    """free, held-by-me, held-by-other, or expired, for one Canvas.

    Two hosts that acquire before either has synced can leave two lines for one
    Canvas once Sync merges the Markdown. Any unexpired line from another device
    then counts as held by other, so both hosts stop rather than both writing.
    """
    canvas = canvas.expanduser().resolve()
    me, source = (device, "argument") if device else device_name(config_path)
    moment = _now(now)
    path = lease_file(canvas)
    entries = [entry for entry in _read_entries(path) if entry["canvas"] == canvas.name]
    live = [entry for entry in entries if _parse_time(entry["expires_at"], path) > moment]
    foreign = [entry for entry in live if entry["device"] != me]
    mine = [entry for entry in live if entry["device"] == me]
    if foreign:
        state, pool = "held-by-other", foreign
    elif mine:
        state, pool = "held-by-me", mine
    elif entries:
        state, pool = "expired", entries
    else:
        state, pool = "free", []
    entry = max(pool, key=lambda item: item["expires_at"]) if pool else {}
    return {
        "canvas": str(canvas),
        "lease_file": str(path),
        "device": me,
        "device_source": source,
        "state": state,
        "holder": entry.get("device"),
        "acquired_at": entry.get("acquired_at"),
        "expires_at": entry.get("expires_at"),
        "purpose": entry.get("purpose"),
        "required": lease_required(canvas),
    }


def _held_message(status: dict[str, Any]) -> str:
    purpose = f" for {status['purpose']!r}" if status.get("purpose") else ""
    return (
        f"{Path(status['canvas']).name} is leased by device {status['holder']!r}{purpose} "
        f"until {status['expires_at']}; this device is {status['device']!r}. "
        "Wait for the lease to expire or ask the user; never release another device's lease yourself"
    )


def acquire_lease(
    canvas: Path,
    *,
    minutes: int = 30,
    purpose: str | None = None,
    device: str | None = None,
    now: datetime | None = None,
    config_path: Path | None = None,
) -> dict[str, Any]:
    canvas = canvas.expanduser().resolve()
    if not canvas.is_file():
        raise LeaseError(f"Canvas does not exist: {canvas}")
    if not isinstance(minutes, int) or minutes <= 0:
        raise LeaseError("lease minutes must be a positive integer")
    moment = _now(now)
    status = lease_status(canvas, device=device, now=moment, config_path=config_path)
    if status["state"] == "held-by-other":
        raise LeaseError(_held_message(status))
    path = lease_file(canvas)
    renewing = status["state"] == "held-by-me"
    entry: dict[str, Any] = {
        "canvas": canvas.name,
        "device": status["device"],
        "acquired_at": status["acquired_at"] if renewing else _format_time(moment),
        "expires_at": _format_time(moment + timedelta(minutes=minutes)),
    }
    kept_purpose = purpose if purpose is not None else (status["purpose"] if renewing else None)
    if kept_purpose:
        entry["purpose"] = kept_purpose
    others = [item for item in _read_entries(path) if item["canvas"] != canvas.name]
    _write_entries(path, [*others, entry])
    result = lease_status(canvas, device=status["device"], now=moment, config_path=config_path)
    return {**result, "device_source": status["device_source"], "action": "renewed" if renewing else "acquired"}


def release_lease(
    canvas: Path,
    *,
    force: bool = False,
    device: str | None = None,
    now: datetime | None = None,
    config_path: Path | None = None,
) -> dict[str, Any]:
    canvas = canvas.expanduser().resolve()
    moment = _now(now)
    status = lease_status(canvas, device=device, now=moment, config_path=config_path)
    foreign = status["state"] == "held-by-other"
    if foreign and not force:
        raise LeaseError(
            _held_message(status) + ". Only the user may decide to take it with --force"
        )
    path = lease_file(canvas)
    entries = _read_entries(path)
    remaining = [item for item in entries if item["canvas"] != canvas.name]
    if len(remaining) == len(entries):
        action = "not-held"
    else:
        _write_entries(path, remaining)
        action = "force-released" if foreign else "released"
    if foreign:
        append_action(
            canvas.parent / "CANVAS_ACTION_LOG.md",
            status="done",
            action="force-release-lease",
            target=str(canvas),
            reason=f"released by device {status['device']!r} with --force",
            result=f"Removed the lease held by {status['holder']!r} until {status['expires_at']}",
        )
    result = lease_status(canvas, device=status["device"], now=moment, config_path=config_path)
    return {**result, "device_source": status["device_source"], "action": action}


def write_permission(status: dict[str, Any]) -> tuple[str | None, str | None]:
    """(error, warning) for applying a patch under this lease status."""
    name = Path(status["canvas"]).name
    if status["state"] == "held-by-other":
        return _held_message(status), None
    if status["state"] == "held-by-me":
        return None, None
    if status["required"]:
        return (
            f"project.md sets canvas_lease: required and device {status['device']!r} holds no lease on {name}; "
            f"run `obs_paper.py lease acquire {status['canvas']}`, wait until Sync has carried {LEASE_FILE} "
            "to the other hosts, then apply",
            None,
        )
    return None, (
        f"applied without a lease on {name}: project.md does not set canvas_lease: required. "
        "A project written from more than one host should set it"
    )
